package sign;

import javax.sound.sampled.AudioFormat;
import javax.sound.sampled.AudioInputStream;
import javax.sound.sampled.AudioSystem;
import javax.sound.sampled.SourceDataLine;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.util.ArrayList;
import java.util.List;

/**
 * Plays sound effects from memory and mixes them, so overlapping effects all sound
 * (the original signlink wrote each to disk and played one at a time, dropping the rest).
 */
public final class WaveMixer implements Runnable {
	private static final float RATE = 22050f;
	private static final int CHUNK = 256; // frames per mix pass (~12 ms)

	private static final class Voice {
		final short[] pcm;
		int pos;

		Voice(short[] pcm) {
			this.pcm = pcm;
		}
	}

	private final List<Voice> voices = new ArrayList<Voice>();
	private final SourceDataLine line;
	private volatile int volume = 128; // 0..128, from signlink.wavevol

	public WaveMixer() throws Exception {
		AudioFormat fmt = new AudioFormat(RATE, 16, 1, true, false);
		line = AudioSystem.getSourceDataLine(fmt);
		line.open(fmt, CHUNK * 2 * 8); // ~90 ms buffer
		line.start();
		Thread t = new Thread(this, "WaveMixer");
		t.setDaemon(true);
		t.start();
	}

	public void setVolume(int volume) {
		this.volume = Math.max(0, Math.min(128, volume));
	}

	/** Decodes a .wav image (as generated by the client) and starts it playing. */
	public void play(byte[] wav, int len) {
		short[] pcm = decode(wav, len);
		if (pcm == null || pcm.length == 0) {
			return;
		}
		synchronized (voices) {
			voices.add(new Voice(pcm));
		}
	}

	private static short[] decode(byte[] wav, int len) {
		try {
			AudioInputStream in = AudioSystem.getAudioInputStream(new ByteArrayInputStream(wav, 0, len));
			AudioFormat target = new AudioFormat(RATE, 16, 1, true, false);
			if (!in.getFormat().matches(target)) {
				in = AudioSystem.getAudioInputStream(target, in);
			}
			ByteArrayOutputStream out = new ByteArrayOutputStream();
			byte[] buf = new byte[8192];
			int n;
			while ((n = in.read(buf)) > 0) {
				out.write(buf, 0, n);
			}
			byte[] b = out.toByteArray();
			short[] pcm = new short[b.length / 2];
			for (int i = 0; i < pcm.length; i++) {
				pcm[i] = (short) ((b[i * 2] & 0xff) | (b[i * 2 + 1] << 8));
			}
			return pcm;
		} catch (Exception e) {
			return null;
		}
	}

	@Override
	public void run() {
		int[] mix = new int[CHUNK];
		byte[] out = new byte[CHUNK * 2];
		while (true) {
			java.util.Arrays.fill(mix, 0);
			boolean any;
			synchronized (voices) {
				any = !voices.isEmpty();
				for (int v = voices.size() - 1; v >= 0; v--) {
					Voice voice = voices.get(v);
					int n = Math.min(CHUNK, voice.pcm.length - voice.pos);
					for (int i = 0; i < n; i++) {
						mix[i] += voice.pcm[voice.pos + i];
					}
					voice.pos += n;
					if (voice.pos >= voice.pcm.length) {
						voices.remove(v);
					}
				}
			}
			if (!any) {
				try {
					Thread.sleep(5L);
				} catch (InterruptedException ignore) {
				}
				continue;
			}
			int vol = volume;
			for (int i = 0; i < CHUNK; i++) {
				int s = mix[i] * vol >> 7;
				if (s > 32767) {
					s = 32767;
				} else if (s < -32768) {
					s = -32768;
				}
				out[i * 2] = (byte) s;
				out[i * 2 + 1] = (byte) (s >> 8);
			}
			line.write(out, 0, out.length); // blocks, pacing the loop to real time
		}
	}
}
